const choose = <T,>(items: readonly T[]): T =>
  items[Math.floor(Math.random() * items.length)];

const givenNamesForGender = (gender: CharacterGender) => {
  if (gender === "female") return femaleGivenNames;
  return maleGivenNames;
};

export const randomCharacterGender = (): CharacterGender =>
  choose(characterGenders);

export const generateHumanName = (
  gender: CharacterGender = randomCharacterGender(),
): GeneratedCharacterName => {
  const givenName = choose(givenNamesForGender(gender));
  const familyName = choose(familyNames);

  return {
    gender,
    givenName,
    familyName,
    name: `${givenName} ${familyName}`,
  };
};

export const isPlaceholderCharacterName = (name: string) =>
  name.trim().length === 0 || name.trim() === "Unnamed Traveller";
